/// Names the cause behind repeated plugin repairs, when it's the phase older Tuist generated.
struct MacroCopyPhaseCheck: Check {
    let id = "xcode-mcp/macro-copy-phase"
    let title = "No in-place macro copy phase"

    func run(_ context: CheckContext) async -> CheckResult {
        let projects = MacroCopyPhase.projects(in: context.project)
        guard !projects.isEmpty else { return .pass("none") }
        return .warn("\(projects.joined(separator: ", ")) still copy macro plugins in place, which gets them killed: generated by Tuist before 4.203; upgrade Tuist and regenerate")
    }
}
