import Foundation

import XcrewCore

struct RepairMacrosCommand: Command {
    let name = "repair-macros"
    let usage = ["repair-macros [--check]   re-copy macro plugins macOS killed at launch (--check: report only)"]

    func run(_ invocation: Invocation) async throws -> Int32 {
        let context = invocation.context
        let locator = MacroPluginLocator(project: context.project, machine: context.machine)
        let repairer = MacroPluginRepairer(locator: locator, probe: CapabilityProbe(runner: context.runner))
        if invocation.arguments.has("check") {
            let dead = await repairer.deadPlugins()
            dead.forEach { invocation.print("dead: \($0.label)") }
            return dead.isEmpty ? 0 : 1
        }
        let report = await repairer.repair()
        report.repaired.forEach { invocation.print("repaired: \($0)") }
        report.stillDead.forEach { invocation.print("still dead: \($0)") }
        if report.isEmpty { invocation.print("all \(locator.plugins().count) macro plugins answer") }
        let cause = MacroCopyPhase.projects(in: context.project)
        if !report.repaired.isEmpty, !cause.isEmpty {
            invocation.print("cause: \(cause.joined(separator: ", ")) were generated by Tuist before 4.203, whose macro copy phase overwrites plugins in place; upgrade Tuist and regenerate")
        }
        return report.stillDead.isEmpty ? 0 : 1
    }
}
